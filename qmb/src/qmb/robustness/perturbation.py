def _coerce_candles(value: object) -> Result[tuple[Candle, ...]]:
    if isinstance(value, Candle):
        items: Sequence[object] = (value,)
    elif isinstance(value, (str, bytes, bytearray)) or not isinstance(value, Sequence):
        return invalid(
            "candles",
            "candle-perturbation reads the replay run's ordered OHLC candle series",
            given=repr(type(value).__name__),
        )
    else:
        items = cast("Sequence[object]", value)
    out: list[Candle] = []
    previous_ns: int | None = None
    for index, item in enumerate(items):
        parsed = _candle_from(item, index)
        if is_refusal(parsed):
            return parsed
        candle = parsed.value
        if previous_ns is not None and candle.instant.value_ns <= previous_ns:
            return invalid(
                "candles",
                "candles are strictly increasing in Instant order (a real historical series)",
                index=index,
                instant_ns=candle.instant.value_ns,
                previous_ns=previous_ns,
            )
        previous_ns = candle.instant.value_ns
        out.append(candle)
    if not out:
        return invalid(
            "candles",
            "candle-perturbation re-runs over a non-empty real candle series; an empty "
            "series has no history to perturb (AC1)",
        )
    return Ok(tuple(out))


def _candle_from(item: object, index: int) -> Result[Candle]:
    if isinstance(item, Candle):
        return Ok(item)
    if not isinstance(item, Mapping):
        return invalid(
            "candles",
            "every candle is a Candle or a mapping of instant, open, high, low, close",
            index=index,
            given=repr(type(item).__name__),
        )
    body = cast("Mapping[str, object]", item)
    minted = Candle.try_create(
        body.get("instant"),
        body.get("open"),
        body.get("high"),
        body.get("low"),
        body.get("close"),
    )
    if is_refusal(minted):
        return invalid(
            "candles",
            "each candle is a valid strictly-positive OHLC print",
            index=index,
            cause=dict(minted.context),
        )
    return minted


def _coerce_scenarios(value: object) -> Result[tuple[PerturbationScenario, ...]]:
    if isinstance(value, PerturbationScenario):
        return Ok((value,))
    if isinstance(value, (str, bytes, bytearray)) or not isinstance(value, Sequence):
        return invalid(
            "scenarios",
            "the fan-out reads a sequence of PerturbationScenario descriptors",
            given=repr(type(value).__name__),
        )
    out: list[PerturbationScenario] = []
    for index, item in enumerate(cast("Sequence[object]", value)):
        if not isinstance(item, PerturbationScenario):
            return invalid(
                "scenarios",
                "each scenario is a PerturbationScenario built by perturbation_scenarios",
                index=index,
                given=repr(type(item).__name__),
            )
        out.append(item)
    if not out:
        return invalid("scenarios", "a scenario fan-out has at least one scenario")
    return Ok(tuple(out))


def _resolve_configurable(config: object, explicit: object, key: str, field: str) -> Result[int]:
    """Resolve a required positive-int configurable from the config key or an explicit arg.

    Neither the block length nor the scenario count has a ratified value (SC-07); an
    unset input is a typed ``invalid input`` refusal, never a silently-applied default.
    """
    if config is not None:
        return require_positive_int(config, key)
    if explicit is not None:
        return _positive_int(explicit, field)
    return invalid(
        field,
        "this input is a UI-editable configurable with no ratified value; supply it via the "
        "resolved run-config key or explicitly (SC-07)",
        configurable_key=key,
    )


def _resolve_seed_price(value: object, candles: tuple[Candle, ...]) -> Result[int]:
    """The cumulative-sum seed price, defaulting to the first candle's open (AC1)."""
    if value is None:
        return Ok(candles[0].open)
    return _positive_int(value, "seed_price")


def _optional_run_root(value: object) -> Result[str]:
    if value is None:
        return Ok("")
    if isinstance(value, Fingerprint):
        return Ok(value.value)
    token = clean_token(value)
    if token is None:
        return invalid(
            "run_root",
            "the parent run root is a Fingerprint or its fp1 token",
            given=repr(value),
        )
    return Ok(token)


def _non_negative_int(value: object, field: str) -> Result[int]:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        return invalid(field, "a non-negative exact integer is required", given=repr(value))
    return Ok(value)


def _positive_int(value: object, field: str) -> Result[int]:
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        return invalid(field, "a positive exact integer is required", given=repr(value))
    return Ok(value)
