"""Monte Carlo candle-perturbation — the alternate-history B-14 rung (Story 22.3).

The second ladder procedure (22.3) re-runs the backtest across resampled market
paths generated by a **real-seeded moving-block bootstrap of OHLC deltas**, so the
operator can see how the strategy holds up under alternate but short-horizon-
consistent market histories (not merely a re-order of realised trades, as
22.2 does).

What the procedure is:

* a **pure library function** (:func:`run_candle_perturbation`) under the B-14
  contract — it consumes a ``world = replay`` run's real historical candles,
  RETURNS its result, and writes no log and no ledger line (the Epic 15
  orchestrator owns every append). Unlike the trade-shuffle rung it **does** mint a
  synthetic market series, but that series is **procedure-ephemeral**: it is never
  persisted into a data room, so the run stays ``world = replay`` and its provenance
  is ``procedure-ephemeral`` (B-7; AC1, AC2);
* a **moving-block bootstrap of exact-integer OHLC delta tuples** (AC1): each candle
  is reduced to the exact-integer offsets ``(open, high, low, close) - anchor`` from
  its anchor price (the previous close; the seed price for the first candle). A
  scenario resamples overlapping length-``L`` blocks of those delta tuples, then
  **cumulative-sums** them back onto the seed price with exact-integer money math
  (AD-7). Because a whole delta tuple is a rigid translation, each rebuilt candle
  keeps its internal shape; the rebuild additionally **enforces high/low bounds** and
  shifts any candle whose low would fall to or below zero so the series is always
  valid and **strictly positive**. **Scenario 0 is the true history** — it bypasses
  resampling and returns the real candles verbatim;
* the **block length is a UI-editable configurable with no ratified value** (SC-07,
  AC1): it resolves from the run-config's ``qmb_mc_candle_perturbation_block_length``
  key or an explicit argument; unset, it is a typed ``invalid input`` refusal, never
  a silently-applied default. The scenario count is likewise configurable;
* **per-scenario reproducibility** (AR-59; NFR-03; AC4): scenario ``s`` resamples
  with a fresh :class:`random.Random` seeded ``base_seed + s`` — no module-global
  RNG — and the result records the RNG family, seed-derivation rule, block length,
  scenario count, resampling scheme, and data-window UTC-ns bounds. Re-running the
  same inputs reproduces the result fingerprint bit-for-bit, or refuses;
* the **persistence law** (B-7, GAP-0048; AC2, AC3): the ephemeral perturbation
  stays ``world = replay`` and its claim class is robustness-only. A config that
  instead requests **persisting** the synthetic series compiles to ``world =
  simulated`` and is a typed ``policy rejection`` for governed evidence — it cannot
  ledger into the bar's store until GAP-0048 closes (SC-06). A config binding a
  ``replay`` clock to synthetic-tainted persisted data is a typed ``invalid input``
  (B-2/B-7 wins, FM-3, DEC-0164);
* the **governed fan-out** (B-5, AR-50, AR-51; AC5): scenarios fan out under the
  orchestrator's process-per-run governor bounded by ``min(cpu, memory)`` with
  enqueue-when-full and a cancel token — no Ray, no daemon, no required Docker. The
  orchestrator appends exactly one ``role = replicate`` ledger line per scenario with
  the objective measure, never a bar verdict (B-4);
* the **distribution summary** (AC6): the per-scenario objective measure is
  summarised with the Story 22.1 primitive — percentiles, confidence bands, and the
  direction-aware empirical percentile rank of the true result within the
  alternate-history distribution — as chart series data, never a verdict. The claim
  class is robustness (alternate-history), never edge (L20), and the result cannot
  gate live money.
"""

