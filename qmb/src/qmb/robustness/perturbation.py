# --- the per-scenario synthetic series (procedure-ephemeral, AC1) -------------


@dataclass(frozen=True, slots=True)
class SyntheticCandleSeries:
    """One scenario's synthetic candle series — procedure-ephemeral, never persisted.

    Scenario 0 (``is_true_history``) is the real candles verbatim; every other
    scenario is a moving-block-bootstrapped alternate history. ``fingerprint`` is the
    ``fp1`` over the candle series; the run result folds only this fingerprint into
    its identity, never the full candles.
    """

    scenario_index: int
    is_true_history: bool
    candles: tuple[Candle, ...]
    fingerprint: Fingerprint

    def fp1_identity(self) -> dict[str, object]:
        """Canonical series identity content — the full candle sequence."""
        return {
            "candles": [candle.fp1_identity() for candle in self.candles],
            "class": _SYNTHETIC_SERIES_CLASS,
            "is_true_history": self.is_true_history,
            "scenario_index": self.scenario_index,
        }


# --- the objective distribution summary (AC6) --------------------------------


@dataclass(frozen=True, slots=True)
class AlternateHistoryDistribution:
    """The objective measure summarised across the alternate histories, as data (AC6).

    ``summary`` is the Story 22.1 distribution primitive — percentiles, confidence
    bands, and a direction-aware one-tailed p-value — over the perturbed scenarios'
    objective values against the true (scenario 0) result.
    ``observed_favorable_rank`` is the direction-aware empirical percentile rank of the
    true result within the alternate-history distribution. ``distribution`` is a
    histogram-ready array of the scenario objective values — chart series as data,
    never an image, AD-10-excluded from identity. No pass/fail verdict is emitted.
    """

    objective_identity: str
    direction: str
    unit_kind: str
    scenario_count: int
    summary: DistributionSummary
    observed_favorable_rank_num: int
    observed_favorable_rank_den: int
    distribution: HistogramReadyArray

    @property
    def observed_favorable_rank(self) -> Fraction:
        """The direction-aware empirical percentile rank of the true result (0..1)."""
        return Fraction(self.observed_favorable_rank_num, self.observed_favorable_rank_den)

    @property
    def emits_verdict(self) -> bool:
        """Always ``False`` — the objective distribution is pure data (AC6)."""
        return PERTURBATION_EMITS_VERDICT

    def chart_series(self) -> dict[str, object]:
        """The scenario distribution as machine-readable chart series (never an image)."""
        return self.distribution.as_data()

    def fp1_identity(self) -> dict[str, object]:
        """Canonical identity content. The histogram array is display-only, excluded."""
        return {
            "canonical_payload": PERTURBATION_CANONICAL_PAYLOAD,
            "class": _OBJECTIVE_DISTRIBUTION_CLASS,
            "direction": self.direction,
            "emits_image_payload": PERTURBATION_EMITS_IMAGE_PAYLOAD,
            "emits_verdict": PERTURBATION_EMITS_VERDICT,
            "objective_identity": self.objective_identity,
            "observed_favorable_rank_den": self.observed_favorable_rank_den,
            "observed_favorable_rank_num": self.observed_favorable_rank_num,
            "scenario_count": self.scenario_count,
            "summary": self.summary.fp1_identity(),
            "unit_kind": self.unit_kind,
        }


def summarize_perturbation_objective(
    *,
    objective_identity: object,
    observed: object,
    scenario_objectives: object,
    direction: object,
    band_probabilities: object = (),
) -> Result[AlternateHistoryDistribution]:
    """Summarise the objective measure across the alternate histories, as data (AC6).

    ``observed`` is the true-history (scenario 0) objective; ``scenario_objectives``
    is the objective measure of each perturbed scenario. Every value is an exact
    quantity — ``Money``, an ``ExactRational``, an ``int``, or a ``Fraction`` — sharing
    the observed value's unit-kind. Returns percentiles, confidence bands, and the
    direction-aware empirical percentile rank of the true result within the
    distribution. No pass/fail verdict is emitted and no alpha level is invented.
    """
    label = clean_token(objective_identity)
    if label is None:
        return invalid(
            "objective_identity",
            "the summarised objective names a non-blank measure identity",
            given=repr(objective_identity),
        )
    dir_token = _direction_token(direction)
    if is_refusal(dir_token):
        return dir_token
    observed_pv = _as_point_value(observed, field="observed")
    if is_refusal(observed_pv):
        return observed_pv
    unit_kind = observed_pv.value.unit_kind
    scenarios = _coerce_objectives(scenario_objectives, unit_kind)
    if is_refusal(scenarios):
        return scenarios
    values = scenarios.value
    if not values:
        return invalid(
            "scenario_objectives",
            "summarising the objective needs at least one perturbed-scenario value; an "
            "empty required input is invalid, never a silently-applied default (AR-13)",
        )
    summary = summarize_distribution(
        values,
        observed_pv.value,
        dir_token.value,
        band_probabilities=band_probabilities,
    )
    if is_refusal(summary):
        return summary
    favorable = _favorable_rank(summary.value.percentile_rank, dir_token.value)
    distribution = HistogramReadyArray(
        name=f"{label}_alternate_history_distribution",
        unit_kind=unit_kind,
        values=values,
    )
    return Ok(
        AlternateHistoryDistribution(
            objective_identity=label,
            direction=dir_token.value,
            unit_kind=unit_kind.value,
            scenario_count=len(values),
            summary=summary.value,
            observed_favorable_rank_num=favorable.numerator,
            observed_favorable_rank_den=favorable.denominator,
            distribution=distribution,
        )
    )


# --- the result (AC1, AC2, AC4, AC6) -----------------------------------------


@dataclass(frozen=True, slots=True)
class CandlePerturbationResult:
    """The Monte Carlo candle-perturbation result of one replay run (AC1, AC2, AC4, AC6).

    ``provenance`` records the RNG family, base seed, seed rule, block length,
    scenario count, resampling scheme, and data-window bounds; ``scenarios`` are the
    governed replicate descriptors; ``series`` carries each scenario's
    procedure-ephemeral synthetic candles (scenario 0 is the true history);
    ``objective`` is the alternate-history distribution summary when the objective was
    supplied. The whole object mints a synthetic series but never persists it, stays
    ``world = replay``, and is a pure deterministic function of its inputs —
    :meth:`fingerprint` reproduces bit-for-bit (AC4). It makes no edge claim and emits
    no verdict.
    """

    procedure: str
    mode: str
    world: str
    base_seed: int
    seed_price: int
    block_length: int
    scenario_count: int
    provenance: PerturbationProvenance
    scenarios: tuple[PerturbationScenario, ...]
    series: tuple[SyntheticCandleSeries, ...]
    objective: AlternateHistoryDistribution | None = None

    @property
    def emits_verdict(self) -> bool:
        """Always ``False`` — the result is pure data, never a verdict (AC6)."""
        return PERTURBATION_EMITS_VERDICT

    @property
    def mints_synthetic_series(self) -> bool:
        """Always ``True`` — the perturbation mints a synthetic market series (AC1)."""
        return PERTURBATION_MINTS_SYNTHETIC_SERIES

    @property
    def persists_synthetic_series(self) -> bool:
        """Always ``False`` — the synthetic series is procedure-ephemeral (AC2)."""
        return PERTURBATION_PERSISTS_SYNTHETIC_SERIES

    @property
    def claim_class(self) -> str:
        """Always robustness (alternate-history), never edge (L20, AC6)."""
        return PERTURBATION_CLAIM_CLASS

    def true_history(self) -> SyntheticCandleSeries:
        """Scenario 0 — the real candles verbatim (AC1)."""
        return self.series[0]

    def series_at(self, scenario_index: int) -> SyntheticCandleSeries | None:
        """The synthetic series for ``scenario_index``, or ``None`` if out of range."""
        for item in self.series:
            if item.scenario_index == scenario_index:
                return item
        return None

    def rng_provenance(self) -> dict[str, object]:
        """The ``rng_provenance`` stamp the CT-32 label folds in (B-13, AR-59)."""
        return self.provenance.fp1_identity()

    def result_label(self) -> dict[str, object]:
        """The procedure identity plus seed that enter the result label (B-7, AC2)."""
        return {
            "base_seed": self.base_seed,
            "claim_class": PERTURBATION_CLAIM_CLASS,
            "class": PERTURBATION_RESULT_CLASS,
            "mints_synthetic_series": PERTURBATION_MINTS_SYNTHETIC_SERIES,
            "mode": self.mode,
            "persists_synthetic_series": PERTURBATION_PERSISTS_SYNTHETIC_SERIES,
            "procedure": self.procedure,
            "provenance_kind": PERTURBATION_PROVENANCE_KIND,
            "resampling_scheme": RESAMPLING_SCHEME,
            "rng_family": self.provenance.rng_family,
            "world": self.world,
        }

    def fp1_identity(self) -> dict[str, object]:
        """Canonical identity content. Deterministic and reproducible (AC4, NFR-03).

        The per-scenario synthetic candles are folded in only by their series
        fingerprint (not the full candle sequences), keeping identity bounded while
        staying a pure function of the inputs.
        """
        content: dict[str, object] = {
            "base_seed": self.base_seed,
            "block_length": self.block_length,
            "canonical_payload": PERTURBATION_CANONICAL_PAYLOAD,
            "claim_class": PERTURBATION_CLAIM_CLASS,
            "class": PERTURBATION_RESULT_CLASS,
            "emits_image_payload": PERTURBATION_EMITS_IMAGE_PAYLOAD,
            "emits_verdict": PERTURBATION_EMITS_VERDICT,
            "format_version": PERTURBATION_RESULT_FORMAT_VERSION,
            "makes_edge_claim": PERTURBATION_MAKES_EDGE_CLAIM,
            "mints_synthetic_series": PERTURBATION_MINTS_SYNTHETIC_SERIES,
            "mode": self.mode,
            "persists_synthetic_series": PERTURBATION_PERSISTS_SYNTHETIC_SERIES,
            "procedure": self.procedure,
            "provenance": self.provenance.fp1_identity(),
            "resampling_scheme": RESAMPLING_SCHEME,
            "scenario_count": self.scenario_count,
            "scenarios": [scenario.fp1_identity() for scenario in self.scenarios],
            "seed_price": self.seed_price,
            "series_fingerprints": [item.fingerprint.value for item in self.series],
            "world": self.world,
        }
        if self.objective is not None:
            content["objective"] = self.objective.fp1_identity()
        return content

    def fingerprint(self) -> Result[Fingerprint]:
        """Content fingerprint. The same inputs reproduce it bit-for-bit (AC4)."""
        return fingerprint(self.fp1_identity())


def run_candle_perturbation(
    *,
    candles: object,
    base_seed: object,
    block_length: object = None,
    scenario_count: object = None,
    config: object = None,
    seed_price: object = None,
    run_root: object = None,
    objective_identity: object = None,
    scenario_objectives: object = None,
    objective_direction: object = None,
    band_probabilities: object = (),
) -> Result[CandlePerturbationResult]:
    """Run the Monte Carlo candle-perturbation over a replay run's candles (AC1-AC6).

    ``candles`` is the ``world = replay`` run's real historical OHLC series. The block
    length and scenario count are UI-editable configurables resolved from ``config``
    (the ``qmb_mc_candle_perturbation_block_length`` and
    ``qmb_mc_candle_perturbation_scenarios`` keys) or passed explicitly — neither has
    a ratified value (SC-07). Each scenario moving-block-bootstraps exact-integer OHLC
    deltas with a ``base_seed + scenario_index`` seeded generator and cumulative-sums
    them onto the seed price, always rebuilding a valid strictly-positive series;
    scenario 0 is the true history. No synthetic series is persisted, so the run stays
    ``world = replay`` (B-7). When ``scenario_objectives`` (one exact objective value
    per scenario, index-aligned) and ``objective_direction`` are supplied, the
    objective is summarised across the alternate histories against the true result. No
    verdict is emitted.
    """
    resolved_block = _resolve_configurable(config, block_length, BLOCK_LENGTH_KEY, "block_length")
    if is_refusal(resolved_block):
        return resolved_block
    resolved_count = _resolve_configurable(
        config, scenario_count, PERTURBATION_SCENARIO_COUNT_KEY, "scenario_count"
    )
    if is_refusal(resolved_count):
        return resolved_count
    base = _non_negative_int(base_seed, "base_seed")
    if is_refusal(base):
        return base
    parsed_candles = _coerce_candles(candles)
    if is_refusal(parsed_candles):
        return parsed_candles
    true_candles = parsed_candles.value
    seed = _resolve_seed_price(seed_price, true_candles)
    if is_refusal(seed):
        return seed
    block = resolved_block.value
    if block > len(true_candles):
        return invalid(
            "block_length",
            "the moving-block bootstrap block length cannot exceed the candle count; a "
            "block must fit inside the data window (AC1)",
            block_length=block,
            candle_count=len(true_candles),
        )
    deltas = ohlc_deltas(true_candles, seed_price=seed.value)
    if is_refusal(deltas):
        return deltas
    timeline = tuple(candle.instant for candle in true_candles)
    descriptors = perturbation_scenarios(base.value, resolved_count.value, run_root=run_root)
    if is_refusal(descriptors):
        return descriptors
    built_series = _build_scenarios(
        true_candles=true_candles,
        deltas=deltas.value,
        timeline=timeline,
        seed_price=seed.value,
        base_seed=base.value,
        scenario_count=resolved_count.value,
        block_length=block,
    )
    if is_refusal(built_series):
        return built_series
    objective: AlternateHistoryDistribution | None = None
    if scenario_objectives is not None or objective_identity is not None:
        summarised = _summarise_supplied_objective(
            objective_identity=objective_identity,
            scenario_objectives=scenario_objectives,
            objective_direction=objective_direction,
            scenario_count=resolved_count.value,
            band_probabilities=band_probabilities,
        )
        if is_refusal(summarised):
            return summarised
        objective = summarised.value
    provenance = PerturbationProvenance(
        rng_family=RNG_FAMILY,
        base_seed=base.value,
        seed_derivation_rule=SEED_DERIVATION_RULE,
        block_length=block,
        scenario_count=resolved_count.value,
        resampling_scheme=RESAMPLING_SCHEME,
        data_window_start_ns=timeline[0].value_ns,
        data_window_end_ns=timeline[-1].value_ns,
    )
    return Ok(
        CandlePerturbationResult(
            procedure=CANDLE_PERTURBATION_PROCEDURE,
            mode=PERTURBATION_MODE,
            world=World.REPLAY.value,
            base_seed=base.value,
            seed_price=seed.value,
            block_length=block,
            scenario_count=resolved_count.value,
            provenance=provenance,
            scenarios=descriptors.value,
            series=built_series.value,
            objective=objective,
        )
    )


