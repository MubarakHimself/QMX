# --- scenario reconstruction (exact integer money) ---------------------------


def _build_scenarios(
    *,
    true_candles: tuple[Candle, ...],
    deltas: tuple[OHLCDelta, ...],
    timeline: tuple[Instant, ...],
    seed_price: int,
    base_seed: int,
    scenario_count: int,
    block_length: int,
) -> Result[tuple[SyntheticCandleSeries, ...]]:
    """Build every scenario's synthetic series. Scenario 0 is the true history.

    Scenario ``s >= 1`` resamples overlapping length-``block_length`` blocks of the
    OHLC deltas with a fresh ``random.Random(base_seed + s)``, cumulative-sums them
    onto the seed price in exact integer money, and rebuilds a valid strictly-positive
    OHLC series (high/low bounds enforced, a non-positive candle translated up).
    """
    series: list[SyntheticCandleSeries] = []
    for index in range(scenario_count):
        if index == 0:
            candles = true_candles
        else:
            resampled = _resample_deltas(deltas, block_length, base_seed + index)
            rebuilt = _rebuild_candles(resampled, timeline, seed_price)
            if is_refusal(rebuilt):
                return rebuilt
            candles = rebuilt.value
        stamped = fingerprint(
            {
                "candles": [candle.fp1_identity() for candle in candles],
                "class": _SYNTHETIC_SERIES_CLASS,
                "is_true_history": index == 0,
                "scenario_index": index,
            }
        )
        if is_refusal(stamped):
            return stamped
        series.append(
            SyntheticCandleSeries(
                scenario_index=index,
                is_true_history=index == 0,
                candles=candles,
                fingerprint=stamped.value,
            )
        )
    return Ok(tuple(series))


def _resample_deltas(
    deltas: tuple[OHLCDelta, ...],
    block_length: int,
    seed: int,
) -> tuple[OHLCDelta, ...]:
    """Moving-block bootstrap: draw overlapping length-``block_length`` blocks.

    Block starts are uniform over ``[0, n - block_length]`` (overlapping blocks). A
    fresh seeded MT19937 generator draws ``ceil(n / block_length)`` blocks, which are
    concatenated and truncated to ``n`` deltas — never a cryptographic use (AR-59).
    """
    n = len(deltas)
    num_starts = n - block_length + 1
    blocks_needed = -(-n // block_length)  # ceil division
    # A seeded MT19937 generator, one fresh instance per scenario, for a reproducible
    # alternate-history resample — never a cryptographic use (AR-59, AC4).
    rng = random.Random(seed)  # noqa: S311
    resampled: list[OHLCDelta] = []
    for _ in range(blocks_needed):
        start = rng.randrange(num_starts)
        resampled.extend(deltas[start : start + block_length])
    return tuple(resampled[:n])


def _rebuild_candles(
    deltas: tuple[OHLCDelta, ...],
    timeline: tuple[Instant, ...],
    seed_price: int,
) -> Result[tuple[Candle, ...]]:
    """Cumulative-sum resampled deltas onto the seed price into valid candles (AC1).

    The running anchor starts at ``seed_price`` and advances to each rebuilt close.
    High/low bounds are enforced from the four rebuilt prices, and any candle whose
    low would fall to or below zero is translated up so the series stays strictly
    positive.
    """
    anchor = seed_price
    candles: list[Candle] = []
    for index, delta in enumerate(deltas):
        o = anchor + delta.open_delta
        h = anchor + delta.high_delta
        low_v = anchor + delta.low_delta
        c = anchor + delta.close_delta
        high = max(o, h, low_v, c)
        low = min(o, h, low_v, c)
        if low < MINIMUM_POSITIVE_PRICE:
            shift = MINIMUM_POSITIVE_PRICE - low
            o += shift
            c += shift
            high += shift
            low += shift
        built = Candle.try_create(timeline[index], o, high, low, c)
        if is_refusal(built):
            return built
        candles.append(built.value)
        anchor = c
    return Ok(tuple(candles))


# --- objective summarisation helpers (AC6) -----------------------------------


def _summarise_supplied_objective(
    *,
    objective_identity: object,
    scenario_objectives: object,
    objective_direction: object,
    scenario_count: int,
    band_probabilities: object,
) -> Result[AlternateHistoryDistribution | None]:
    """Summarise a caller-supplied per-scenario objective, or refuse a partial request.

    ``scenario_objectives`` is index-aligned to the scenarios (element 0 is the true
    history). The observed value is element 0 and the distribution is elements
    ``1..``. A single-scenario run has no alternate-history distribution and returns
    no objective summary.
    """
    if objective_identity is None:
        return invalid(
            "objective_identity",
            "summarising the objective needs the measure identity alongside the "
            "per-scenario objective values",
        )
    if scenario_objectives is None:
        return invalid(
            "scenario_objectives",
            "summarising the objective needs one objective value per scenario, "
            "index-aligned to the scenarios (element 0 is the true history)",
        )
    if isinstance(scenario_objectives, (str, bytes, bytearray)) or not isinstance(
        scenario_objectives, Sequence
    ):
        return invalid(
            "scenario_objectives",
            "the per-scenario objectives are an ordered sequence of exact values",
            given=repr(type(scenario_objectives).__name__),
        )
    supplied = cast("Sequence[object]", scenario_objectives)
    if len(supplied) != scenario_count:
        return invalid(
            "scenario_objectives",
            "one objective value per scenario is required, index-aligned to the scenarios",
            given=len(supplied),
            scenario_count=scenario_count,
        )
    if scenario_count < 2:
        return Ok(None)
    return _as_optional(
        summarize_perturbation_objective(
            objective_identity=objective_identity,
            observed=supplied[0],
            scenario_objectives=list(supplied[1:]),
            direction=objective_direction,
            band_probabilities=band_probabilities,
        )
    )


def _as_optional(
    result: Result[AlternateHistoryDistribution],
) -> Result[AlternateHistoryDistribution | None]:
    if is_refusal(result):
        return result
    value: AlternateHistoryDistribution | None = result.value
    return Ok(value)


def _favorable_rank(percentile_rank: Fraction, direction: str) -> Fraction:
    """The direction-aware empirical percentile rank of the true result (AC6).

    ``percentile_rank`` is the fraction of the distribution below the observed value.
    Higher-is-better favours a high rank as-is; lower-is-better favours the low side,
    so the favourable fraction is its complement.
    """
    if direction == DIRECTION_LOWER_IS_BETTER:
        return Fraction(1) - percentile_rank
    return percentile_rank


def _direction_token(direction: object) -> Result[str]:
    token = clean_token(direction)
    if token not in (DIRECTION_HIGHER_IS_BETTER, DIRECTION_LOWER_IS_BETTER):
        return invalid(
            "direction",
            "an objective distribution declares direction higher-is-better or lower-is-better",
            given=repr(direction),
            allowed=(DIRECTION_HIGHER_IS_BETTER, DIRECTION_LOWER_IS_BETTER),
        )
    return Ok(token)


def _as_point_value(value: object, *, field: str, index: int | None = None) -> Result[_PointValue]:
    """Coerce an exact objective value to a ``Money`` or ``ExactRational`` point value."""
    context: dict[str, object] = {} if index is None else {"index": index}
    if isinstance(value, bool):
        return invalid(
            field,
            "an objective value is a number, not a boolean",
            given=repr(value),
            **context,
        )
    if isinstance(value, Money):
        return Ok(value)
    if isinstance(value, ExactRational):
        return Ok(value)
    if isinstance(value, int):
        minted = ExactRational.try_create(value, 1, UnitKind.DIMENSIONLESS_RATIO)
        if is_refusal(minted):
            return minted
        return Ok(minted.value)
    if isinstance(value, Fraction):
        minted = ExactRational.try_create(
            value.numerator, value.denominator, UnitKind.DIMENSIONLESS_RATIO
        )
        if is_refusal(minted):
            return minted
        return Ok(minted.value)
    if isinstance(value, float):
        return invalid(
            field,
            "a binary float never enters the objective distribution; carry it through the "
            "return-space carve-out (a label-derived measure) or supply exact Money / rational "
            "(AD-7, NFR-03)",
            given=repr(value),
            **context,
        )
    return invalid(
        field,
        "an objective value is exact Money, an ExactRational, an int, or a Fraction",
        given=repr(type(value).__name__),
        **context,
    )


def _coerce_objectives(value: object, unit_kind: UnitKind) -> Result[tuple[_PointValue, ...]]:
    if isinstance(value, (str, bytes, bytearray)) or not isinstance(value, Sequence):
        return invalid(
            "scenario_objectives",
            "the per-scenario objectives are an ordered sequence of exact values",
            given=repr(type(value).__name__),
        )
    out: list[_PointValue] = []
    for index, item in enumerate(cast("Sequence[object]", value)):
        parsed = _as_point_value(item, field="scenario_objectives", index=index)
        if is_refusal(parsed):
            return parsed
        if parsed.value.unit_kind is not unit_kind:
            return invalid(
                "scenario_objectives",
                "every scenario objective shares the observed value's unit-kind; there is "
                "no silent unit coercion (AD-40)",
                index=index,
                given=parsed.value.unit_kind.value,
                expected=unit_kind.value,
            )
        out.append(parsed.value)
    return Ok(tuple(out))


