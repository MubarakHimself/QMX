# --- the candle and its exact-integer OHLC delta (AC1) -----------------------


@dataclass(frozen=True, slots=True)
class Candle:
    """One OHLC candle with exact strictly-positive scaled-integer prices (AC1).

    ``open``, ``high``, ``low``, and ``close`` are exact scaled integers (AD-7),
    never binary floats. A valid candle brackets its body: ``high`` is the maximum
    and ``low`` the minimum of the four prices, and every price is strictly positive.
    """

    instant: Instant
    open: int
    high: int
    low: int
    close: int

    def fp1_identity(self) -> dict[str, object]:
        """Canonical identity content. Package SemVer never enters."""
        return {
            "class": _CANDLE_CLASS,
            "close": self.close,
            "high": self.high,
            "instant_ns": self.instant.value_ns,
            "low": self.low,
            "open": self.open,
        }

    @classmethod
    def try_create(
        cls,
        instant: object,
        open_price: object,
        high: object,
        low: object,
        close: object,
    ) -> Result[Candle]:
        """Validate one strictly-positive, high/low-bounded OHLC candle."""
        if not isinstance(instant, Instant):
            return invalid(
                "instant",
                "a candle is timestamped with an Instant (int64 UTC-ns)",
                given=repr(type(instant).__name__),
            )
        prices = {"open": open_price, "high": high, "low": low, "close": close}
        parsed: dict[str, int] = {}
        for field, value in prices.items():
            checked = _positive_int(value, field)
            if is_refusal(checked):
                return checked
            parsed[field] = checked.value
        o, h, low_v, c = parsed["open"], parsed["high"], parsed["low"], parsed["close"]
        if h < max(o, c) or h < low_v:
            return invalid(
                "high",
                "a candle high is at least its open, close, and low (high/low bounds)",
                open=o,
                high=h,
                low=low_v,
                close=c,
            )
        if low_v > min(o, c):
            return invalid(
                "low",
                "a candle low is at most its open and close (high/low bounds)",
                open=o,
                high=h,
                low=low_v,
                close=c,
            )
        return Ok(cls(instant=instant, open=o, high=h, low=low_v, close=c))


@dataclass(frozen=True, slots=True)
class OHLCDelta:
    """One exact-integer OHLC delta tuple: ``(O, H, L, C) - anchor`` (AC1).

    The anchor is the previous candle's close (the seed price for the first
    candle). The four offsets are a rigid unit: adding one anchor to all four
    reconstructs a candle whose internal high/low bounds are preserved.
    """

    open_delta: int
    high_delta: int
    low_delta: int
    close_delta: int

    def fp1_identity(self) -> dict[str, object]:
        """Canonical identity content."""
        return {
            "close_delta": self.close_delta,
            "high_delta": self.high_delta,
            "low_delta": self.low_delta,
            "open_delta": self.open_delta,
        }


def ohlc_deltas(candles: object, *, seed_price: object = None) -> Result[tuple[OHLCDelta, ...]]:
    """Reduce a candle series to exact-integer OHLC delta tuples (AC1).

    Delta ``i`` is ``(O_i, H_i, L_i, C_i)`` minus its anchor — the previous
    candle's close, or the ``seed_price`` for ``i = 0`` (defaulting to the first
    candle's open). Cumulative-summing the deltas in their true order back onto the
    seed price reproduces the exact input series.
    """
    parsed = _coerce_candles(candles)
    if is_refusal(parsed):
        return parsed
    series = parsed.value
    seed = _resolve_seed_price(seed_price, series)
    if is_refusal(seed):
        return seed
    deltas: list[OHLCDelta] = []
    anchor = seed.value
    for candle in series:
        deltas.append(
            OHLCDelta(
                open_delta=candle.open - anchor,
                high_delta=candle.high - anchor,
                low_delta=candle.low - anchor,
                close_delta=candle.close - anchor,
            )
        )
        anchor = candle.close
    return Ok(tuple(deltas))


# --- scenario descriptors and the governed fan-out (AC5) ---------------------


@dataclass(frozen=True, slots=True)
class PerturbationScenario:
    """One alternate-history scenario: index, derived seed, replicate run id (AC4, AC5).

    ``role`` is always ``replicate`` — a scenario is a governed replicate run, never a
    bar-verdict run. ``run_id`` is the deterministic fingerprint the governor admits
    and the orchestrator ledgers exactly once. Scenario 0 is the true history.
    """

    scenario_index: int
    seed: int
    run_id: Fingerprint
    is_true_history: bool
    role: str = ROLE_REPLICATE

    def fp1_identity(self) -> dict[str, object]:
        """Canonical scenario identity content. Package SemVer is omitted."""
        return {
            "class": _PERTURBATION_SCENARIO_CLASS,
            "is_true_history": self.is_true_history,
            "role": self.role,
            "run_id": self.run_id.value,
            "scenario_index": self.scenario_index,
            "seed": self.seed,
        }


def perturbation_scenarios(
    base_seed: object,
    scenario_count: object,
    *,
    run_root: object = None,
) -> Result[tuple[PerturbationScenario, ...]]:
    """Build the deterministic scenario descriptors of one perturbation run (AC4, AC5).

    ``scenario_count`` scenarios are numbered ``0..count-1``; scenario ``s`` carries
    seed ``base_seed + s`` and a run id fingerprinted from the procedure, base seed,
    scenario index, and the optional ``run_root`` (the parent run's id) so replicate
    ids never collide across parent runs. Scenario 0 is flagged as the true history.
    """
    base = _non_negative_int(base_seed, "base_seed")
    if is_refusal(base):
        return base
    count = _positive_int(scenario_count, "scenario_count")
    if is_refusal(count):
        return count
    root = _optional_run_root(run_root)
    if is_refusal(root):
        return root
    scenarios: list[PerturbationScenario] = []
    for index in range(count.value):
        seed = base.value + index
        stamped = fingerprint(
            {
                "base_seed": base.value,
                "class": _PERTURBATION_SCENARIO_CLASS,
                "procedure": CANDLE_PERTURBATION_PROCEDURE,
                "role": ROLE_REPLICATE,
                "run_root": root.value,
                "scenario_index": index,
                "seed": seed,
            }
        )
        if is_refusal(stamped):
            return stamped
        scenarios.append(
            PerturbationScenario(
                scenario_index=index,
                seed=seed,
                run_id=stamped.value,
                is_true_history=index == 0,
            )
        )
    return Ok(tuple(scenarios))


def governed_perturbation_requests(
    scenarios: object,
    *,
    projected_peak_memory: object,
    cpu_cost: object = 1,
) -> Result[tuple[GovernedRequest, ...]]:
    """Build the governor requests for a scenario fan-out (B-5, AR-50, AC5).

    Each :class:`PerturbationScenario` becomes one
    :class:`~qmb.orchestrator.governor.GovernedRequest` the orchestrator submits to
    its ``min(cpu, memory)`` resource governor: admitted when it fits, enqueued when
    full (enqueue-on-full), never silently oversubscribed. Process fan-out belongs to
    the orchestrator — no Ray, no daemon, no required Docker — and each governed
    scenario ledgers exactly one ``role = replicate`` line.
    """
    parsed = _coerce_scenarios(scenarios)
    if is_refusal(parsed):
        return parsed
    requests: list[GovernedRequest] = []
    for scenario in parsed.value:
        built = GovernedRequest.try_create(scenario.run_id, projected_peak_memory, cpu_cost)
        if is_refusal(built):
            return built
        requests.append(built.value)
    return Ok(tuple(requests))


def refuse_perturbation_bar_verdict(name: object) -> Result[None]:
    """Refuse reading a bar verdict out of a replicate scenario line (AR-51, AC5).

    A governed scenario appends exactly one ``role = replicate`` ledger line carrying
    the objective measure — never a Book-bar pass/fail. Any attempt to read a bar
    verdict out of it is a ``policy rejection`` (B-4, AR-51).
    """
    token = clean_token(name)
    if token is None:
        return invalid(
            "verdict",
            "a verdict name is required to refuse it",
            given=repr(name),
        )
    return policy(
        "verdict",
        "a candle-perturbation scenario is a role=replicate run appending one ledger line "
        "with the objective measure; it never writes a Book-bar pass/fail verdict (B-4, AR-51)",
        verdict=token,
        role=ROLE_REPLICATE,
        writes_bar_verdict=False,
    )


# --- the B-7 persistence law (AC2, AC3) --------------------------------------


@dataclass(frozen=True, slots=True)
class PerturbationPersistence:
    """The compiled persistence classification of a perturbation run (AC2, AC3).

    The only OK state is the procedure-ephemeral one: the synthetic series is never
    persisted, the run stays ``world = replay``, provenance is
    ``procedure-ephemeral``, and the claim class is robustness-only. Every persisting
    configuration is a typed refusal, never an Ok value.
    """

    world: str
    data_provenance: str
    claim_class: str
    persisted: bool

    def fp1_identity(self) -> dict[str, object]:
        """Canonical persistence identity content."""
        return {
            "claim_class": self.claim_class,
            "class": _PERSISTENCE_CLASS,
            "data_provenance": self.data_provenance,
            "persisted": self.persisted,
            "world": self.world,
        }


def perturbation_persistence(
    *,
    persist: object = False,
    clock: object = CLOCK_REPLAY,
) -> Result[PerturbationPersistence]:
    """Classify a perturbation run by whether it persists its synthetic series (AC2, AC3).

    * ``persist = False`` (the only OK state): the perturbation is procedure-ephemeral
      — ``world = replay``, provenance ``procedure-ephemeral``, claim class robustness
      (AC2). A ``simulated`` clock with no persistence is a mismatch and refuses.
    * ``persist = True`` with a ``simulated`` clock: ``world = simulated`` governed
      evidence — a typed ``policy rejection`` that cannot ledger into the bar's store
      until GAP-0048 closes (SC-06, AC3).
    * ``persist = True`` with a ``replay`` clock: a replay clock bound to
      synthetic-tainted persisted data is a typed ``invalid input`` (B-2/B-7 wins,
      FM-3, DEC-0164, AC3).
    """
    if not isinstance(persist, bool):
        return invalid(
            "persist",
            "persist is an explicit bool: whether the synthetic series is written to a data room",
            given=repr(type(persist).__name__),
        )
    clock_token = clean_token(clock)
    if clock_token not in (CLOCK_REPLAY, CLOCK_SIMULATED):
        return invalid(
            "clock",
            "a perturbation run binds clock replay or simulated",
            given=repr(clock),
            legal=(CLOCK_REPLAY, CLOCK_SIMULATED),
        )
    if not persist:
        if clock_token != CLOCK_REPLAY:
            return invalid(
                "clock",
                "a procedure-ephemeral perturbation stays world=replay; a simulated clock "
                "without persistence is a clock/provenance mismatch (B-7, FM-3)",
                clock=clock_token,
                data_provenance=PROVENANCE_PROCEDURE_EPHEMERAL,
            )
        return Ok(
            PerturbationPersistence(
                world=World.REPLAY.value,
                data_provenance=PROVENANCE_PROCEDURE_EPHEMERAL,
                claim_class=PERTURBATION_CLAIM_CLASS,
                persisted=False,
            )
        )
    if clock_token == CLOCK_REPLAY:
        return refuse_replay_clock_on_synthetic_persisted(clock_token)
    return refuse_persisted_synthetic_series(PERTURBATION_SCENARIO_COUNT_KEY)


def refuse_persisted_synthetic_series(name: object) -> TypedRefusal:
    """Refuse ledgering a persisted synthetic series as governed evidence (SC-06, AC3).

    A config that persists the synthetic series compiles to ``world = simulated`` and
    is a typed ``policy rejection`` for governed evidence: it cannot ledger into the
    bar's store while the GAP-0048 fidelity seam is open. Returned, never raised.
    """
    token = clean_token(name)
    if token is None:
        return invalid(
            "config",
            "a config identity is required to refuse persisting the synthetic series",
            given=repr(name),
        )
    return policy(
        "data_provenance",
        "persisting the synthetic candle series makes the run world=simulated governed "
        "evidence; it is a typed policy rejection that cannot ledger into the bar's store "
        "until GAP-0048 closes (SC-06, B-7)",
        config=token,
        world=World.SIMULATED.value,
        data_provenance=PROVENANCE_SYNTHETIC_TAINTED,
        gated_behind=CLAIM_GATED_BEHIND,
    )


def refuse_replay_clock_on_synthetic_persisted(clock: object) -> TypedRefusal:
    """Refuse a replay clock bound to synthetic-tainted persisted data (B-2/B-7, AC3).

    World is provenance-derived: a ``replay`` clock bound to synthetic-tainted
    persisted data is a typed ``invalid input`` — B-7 (a caller may not declare world)
    and B-2 (the replay clock reads recorded data) win (FM-3, DEC-0164).
    """
    token = clean_token(clock)
    return invalid(
        "clock",
        "a replay clock bound to synthetic-tainted persisted data is invalid input; "
        "world is provenance-derived and B-2/B-7 win (FM-3, DEC-0164)",
        clock=token if token is not None else repr(clock),
        data_provenance=PROVENANCE_SYNTHETIC_TAINTED,
    )


